def district_aliases() -> dict[str, str]:
    """alias → district code; English names first ("Godhra (Panchmahal)" → "godhra (panchmahal)")."""
    out: dict[str, str] = {}
    for code, district in BY_CODE.items():
        out[district.name.lower().split(" (")[0]] = code
        for alias in DISTRICT_NAMES.get(code, []):
            out[alias.lower()] = code
    return out
